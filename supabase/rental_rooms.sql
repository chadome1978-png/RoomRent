-- RoomRent room storage for Supabase.
-- Run in Supabase SQL Editor. The browser app uses only the publishable/anon key;
-- never put service_role credentials in VITE_* variables or client code.

create table if not exists public.rental_rooms (
  id bigint generated by default as identity primary key,
  owner_id uuid not null references auth.users(id) on delete cascade,
  room_number text not null check (length(trim(room_number)) between 1 and 40),
  tenant_name text not null default '',
  phone text not null default '',
  rent_amount numeric(12, 2) not null check (rent_amount >= 0),
  water_rate numeric(10, 2) not null check (water_rate >= 0),
  electric_rate numeric(10, 2) not null check (electric_rate >= 0),
  status text not null check (status in ('occupied', 'vacant', 'archived')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index if not exists rental_rooms_owner_id_idx
  on public.rental_rooms (owner_id);
create unique index if not exists rental_rooms_owner_room_number_lower_uidx
  on public.rental_rooms (owner_id, lower(room_number));

alter table public.rental_rooms enable row level security;

-- Remove/recreate named policies so this script is safe to rerun.
drop policy if exists "Owners can read their rental rooms" on public.rental_rooms;
drop policy if exists "Owners can insert their rental rooms" on public.rental_rooms;
drop policy if exists "Owners can update their rental rooms" on public.rental_rooms;
drop policy if exists "Owners can delete their rental rooms" on public.rental_rooms;

create policy "Owners can read their rental rooms"
  on public.rental_rooms for select to authenticated
  using ((select auth.uid()) = owner_id);

create policy "Owners can insert their rental rooms"
  on public.rental_rooms for insert to authenticated
  with check ((select auth.uid()) = owner_id);

create policy "Owners can update their rental rooms"
  on public.rental_rooms for update to authenticated
  using ((select auth.uid()) = owner_id)
  with check ((select auth.uid()) = owner_id);

create policy "Owners can delete their rental rooms"
  on public.rental_rooms for delete to authenticated
  using ((select auth.uid()) = owner_id);

grant select, insert, update, delete on public.rental_rooms to authenticated;
grant usage, select on sequence public.rental_rooms_id_seq to authenticated;
